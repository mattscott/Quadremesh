using System.Globalization;
using Quadremesh.Core.Math;
using Quadremesh.Core.Mesh;

namespace Quadremesh.IO;

/// <summary>
/// Writes meshes as Wavefront OBJ. Faces are emitted with 1-based indices; positions use
/// round-trippable ("R") formatting so a read-back reproduces the same geometry.
/// </summary>
public static class ObjWriter
{
    /// <summary>Writes a polygon mesh to an OBJ file (LF line endings, for byte-stable output).</summary>
    public static void Write(string path, QuadMesh mesh)
    {
        using var writer = new StreamWriter(path) { NewLine = "\n" };
        Write(writer, mesh);
    }

    /// <summary>Writes a triangle mesh to an OBJ file (LF line endings, for byte-stable output).</summary>
    public static void Write(string path, TriangleMesh mesh)
    {
        using var writer = new StreamWriter(path) { NewLine = "\n" };
        Write(writer, mesh);
    }

    /// <summary>Writes a polygon mesh as OBJ text.</summary>
    public static void Write(TextWriter writer, QuadMesh mesh)
    {
        ArgumentNullException.ThrowIfNull(writer);
        ArgumentNullException.ThrowIfNull(mesh);

        WriteHeader(writer);
        foreach (Vector3 p in mesh.Positions)
        {
            WriteVertex(writer, p);
        }

        for (int f = 0; f < mesh.FaceCount; f++)
        {
            WriteFace(writer, mesh.Face(f));
        }
    }

    /// <summary>Writes a triangle mesh as OBJ text.</summary>
    public static void Write(TextWriter writer, TriangleMesh mesh)
    {
        ArgumentNullException.ThrowIfNull(writer);
        ArgumentNullException.ThrowIfNull(mesh);

        WriteHeader(writer);
        foreach (Vector3 p in mesh.Positions)
        {
            WriteVertex(writer, p);
        }

        Span<int> tri = stackalloc int[3];
        for (int t = 0; t < mesh.TriangleCount; t++)
        {
            (tri[0], tri[1], tri[2]) = mesh.Triangle(t);
            WriteFace(writer, tri);
        }
    }

    private static void WriteHeader(TextWriter writer) =>
        writer.WriteLine("# Generated by Quadremesh.IO");

    private static void WriteVertex(TextWriter writer, Vector3 p) =>
        writer.WriteLine(string.Create(
            CultureInfo.InvariantCulture, $"v {p.X:R} {p.Y:R} {p.Z:R}"));

    private static void WriteFace(TextWriter writer, ReadOnlySpan<int> corners)
    {
        // "f i j k ..." with 1-based indices.
        var sb = new System.Text.StringBuilder("f");
        foreach (int c in corners)
        {
            sb.Append(' ').Append((c + 1).ToString(CultureInfo.InvariantCulture));
        }

        writer.WriteLine(sb.ToString());
    }
}
